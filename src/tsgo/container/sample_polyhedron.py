"""Container geometry.

The five containers are stored as data in ``data/*.json`` rather than as Python
literals, so a new container needs no code change and the geometry is
reviewable in a diff. Each file lists faces with their vertex ring, the inward
normal orientation hint, and any holes; ``Face`` re-derives the unit normal from
the ring and flips it to agree with the hint.

The constructor functions below are thin wrappers kept for backwards
compatibility -- ``cube(radius=...)`` still scales, and ``CONTAINERS`` still maps
the CLI's container names.
"""

import json
import os
from functools import lru_cache
from typing import List, Optional

import numpy as np

from tsgo.container.point import Point
from tsgo.container.face import Face
from tsgo.container.container import Container

# INWARD NORMALS
# X POSITIVE is RIGHT
# Y POSITIVE is BACK
# Z POSITIVE is UP

DATA_DIR = os.path.join(os.path.dirname(__file__), "data")


def _ring(coords, scale: float) -> List[Point]:
    return [Point(scale * c[0], scale * c[1], scale * c[2]) for c in coords]


@lru_cache(maxsize=None)
def _load_spec(path: str) -> str:
    with open(path, "r") as fh:
        return fh.read()


def load_polyhedron(path: str, scale: float = 1.0,
                    description: Optional[str] = None) -> Container:
    """Build a Container from a geometry JSON file.

    Args:
        path: file to read; a bare name is resolved inside ``data/``.
        scale: uniform scale applied to every coordinate.
        description: override the description stored in the file.
    """
    if not os.path.isabs(path) and not os.path.exists(path):
        path = os.path.join(DATA_DIR, path)
    spec = json.loads(_load_spec(path))

    faces = [
        Face(
            _ring(f["vertices"], scale),
            np.asarray(f["normal"], dtype=float),
            f.get("description", ""),
            holes=[_ring(h, scale) for h in f.get("holes", [])] or None,
        )
        for f in spec["faces"]
    ]
    return Container(faces, description=description or spec["description"])


def cube(radius: float = 0.5) -> Container:
    """Axis-aligned cube with half-extent ``radius`` (stored at 0.5)."""
    return load_polyhedron("cube.json", scale=radius / 0.5)


def h_box() -> Container:
    return load_polyhedron("h_box.json")


def triangular_pyramid() -> Container:
    return load_polyhedron("tetrahedron.json")


def pointy_star() -> Container:
    return load_polyhedron("pointy_star.json")


def ribbed_cage() -> Container:
    return load_polyhedron("ribbed_cage.json")


CONTAINERS = {
    "cube": cube,
    "h-box": h_box,
    "tetrahedron": triangular_pyramid,
    "pointy-star": pointy_star,
    "cage": ribbed_cage,
}

# The eight multi-connected containers of Stoyan & Yaskov (2013), examples 1-8,
# generated by tsgo.container.stoyan_yaskov.
for _k in range(1, 9):
    CONTAINERS[f"stoyan-yaskov-{_k}"] = (
        lambda k=_k: load_polyhedron(f"stoyan_yaskov_{k}.json"))
del _k
